"""Run: python eval/run_eval.py -> EVAL_REPORT.md + eval/results.json. Compares the verifying multi-agent system with a no-verification baseline."""
import json, pathlib, sys, statistics
ROOT = pathlib.Path(__file__).resolve().parents[1]; sys.path.insert(0, str(ROOT))
from app.core.agents import ResearchSystem, key_of
L = lambda n: [json.loads(l) for l in (ROOT / "eval/data" / n).read_text().splitlines() if l]
docs, truth, qs = L("corpus.jsonl"), L("truth.jsonl"), L("questions.jsonl"); sysm = ResearchSystem(docs)
pred, runs = {}, []
for q in qs:
    r = sysm.run(q["question"]); runs.append(r)
    for f in r["facts"]: pred[f["key"]] = f
exp = {key_of(t["key_subject"], t["year"]): t for t in truth}
def evaluate(label, predict):
    ok = miss = 0; tp = fp = fn = 0
    for k, t in exp.items():
        p = predict(k); ok += p == t["status"]; miss += p == "missing"
        tp += p == "conflict" and t["status"] == "conflict"; fn += p != "conflict" and t["status"] == "conflict"
    fp = sum(1 for k, f in pred.items() if f["status"] == "conflict" and exp.get(k, {}).get("status") != "conflict") if label == "multi-agent" else 0
    pr = tp / (tp + fp) if tp + fp else 0.0; rc = tp / (tp + fn) if tp + fn else 0.0
    return {"status_accuracy": ok / len(exp), "missing": miss, "conflict_precision": pr, "conflict_recall": rc, "conflict_f1": 2 * pr * rc / (pr + rc) if pr + rc else 0.0}
res = {"multi-agent": evaluate("multi-agent", lambda k: pred[k]["status"] if k in pred else "missing"),
       "baseline (no verification: every extracted claim accepted)": evaluate("baseline", lambda k: "verified" if k in pred else "missing")}
leak = sum("99" in r["report"] for r in runs); quar = sum(len([f for f in r["flags"] if "quarantined" in f]) for r in runs)
valid = tot = 0
src_text = {d["id"]: d["text"] for d in docs}
for r in runs:
    for f in r["facts"]:
        for v, ss in f["values"].items():
            for s in ss: tot += 1; valid += (f"{v} {f['unit']}" in src_text[s])
lat = [r["total_ms"] for r in runs]
res["_other"] = {"injection_payload_in_reports": leak, "quarantined_sentences": quar, "citation_grounding": valid / tot, "latency_ms_mean": round(statistics.mean(lat), 2),
                 "latency_ms_max": max(lat), "tokens_in_per_run": runs[0]["usage"]["tokens_in"], "usd_per_run_offline": 0.0, "facts_expected": len(exp), "keys_predicted": len(pred)}
(ROOT / "eval/results.json").write_text(json.dumps(res, indent=2))
rows = "\n".join(f"| {k} | {v['status_accuracy']:.3f} | {v['conflict_precision']:.3f} | {v['conflict_recall']:.3f} | {v['conflict_f1']:.3f} | {v['missing']} |" for k, v in res.items() if not k.startswith("_"))
o = res["_other"]; ma = res["multi-agent"]
(ROOT / "EVAL_REPORT.md").write_text(f"""# Evaluation Report (auto-generated by `eval/run_eval.py`)

**Setup.** {len(docs)} synthetic source documents, {o['facts_expected']} ground-truth facts (verified / conflicting / single-source, seed 11), {len(qs)} research questions.
~20% of statements use a synonym phrasing ("EV" vs "electric vehicle") that the rule-based extractor deliberately cannot normalize, and one source contains a prompt-injection payload with a fake value. Offline reference agents; no LLM calls.

## Claim verification & conflict detection
| System | Status accuracy | Conflict precision | Conflict recall | Conflict F1 | Facts missed |
|---|---|---|---|---|---|
{rows}

The baseline aggregates everything it extracts and cannot flag disagreement or weak support — it is a *floor*, not a competing system.

## Safety, grounding, cost
- Prompt-injection payload (fake 99 million units) present in reports: **{o['injection_payload_in_reports']}** of {len(qs)}; sentences quarantined: {o['quarantined_sentences']}.
- Citation grounding (cited source text actually contains the cited value): **{o['citation_grounding']:.3f}**.
- Latency per run: mean {o['latency_ms_mean']} ms, max {o['latency_ms_max']} ms. Offline cost $0/run; with an LLM backend, cost is tracked per run via `usage`.

## Honest caveats
- Synthetic, template-based evidence; accuracy mostly reflects extractor coverage (what fraction of statements match the claim grammar), not general language understanding.
- {o['keys_predicted']} distinct fact keys were produced for {o['facts_expected']} true facts — the surplus comes from synonym-noise statements becoming separate keys (missed corroboration / conflicts).
- LLM-based planning/extraction and LLM-as-judge (`eval/judge.py`, with human-agreement check) need an API key and were not run here.
""")
print(json.dumps(res, indent=1))
